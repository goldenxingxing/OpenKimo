"""User-writable Python environment overlay.

The .app's bundled site-packages are read-only and code-signed. To let
users (and the agent's shell tool) `pip install` new packages, we set up
a writable overlay at ~/Library/Application Support/<AppName>/python-userbase
and configure the bundled Python to look there via PYTHONUSERBASE.

This module is idempotent: it can be called every launch and only does work
on first run.
"""

from __future__ import annotations

import functools
import logging
import os
import shlex
import shutil
import stat
import subprocess
import sys
from pathlib import Path

from .paths import AppPaths

log = logging.getLogger(__name__)


def _write_atomic(target: Path, text: str) -> None:
    """Write beside the target and rename over it.

    pip reads its config while the app is writing it — two launches racing,
    or a spawned `pip install` starting mid-write — and a half-written file is
    a parse error rather than a missing setting.
    """
    tmp = target.with_name(f".{target.name}.{os.getpid()}.tmp")
    try:
        tmp.write_text(text)
        os.replace(tmp, target)
    except OSError:
        tmp.unlink(missing_ok=True)
        raise


def _write_pip_conf(p: AppPaths) -> None:
    if p.pip_conf.exists():
        return
    p.pip_conf.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(
        p.pip_conf,
        "# Generated by OpenKimo on first launch.\n"
        "# Forces `pip install` to drop packages into the user overlay\n"
        "# instead of the read-only signed bundle.\n"
        "[install]\n"
        "user = true\n"
        "\n"
        "[global]\n"
        "disable-pip-version-check = true\n",
    )


def _write_wrapper(target: Path, script: str) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    # Beside-then-rename, not in place. setup() rewrites these on every launch
    # while they sit on PATH, and /bin/sh reads a script as it runs it: a
    # truncated-and-refilled shim can be executed half-written by a subprocess
    # that started a moment earlier. os.replace is atomic.
    tmp = target.with_name(f".{target.name}.{os.getpid()}.tmp")
    try:
        tmp.write_text(script)
        tmp.chmod(tmp.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        os.replace(tmp, target)
    except OSError:
        tmp.unlink(missing_ok=True)
        raise


def _ensure_wrappers(p: AppPaths) -> None:
    """Drop `python` / `pip` shims into userbase/bin so PATH-based lookup
    routes through the bundled interpreter and user overlay.
    """
    python_shim = p.userbase_bin / "python"
    pip_shim = p.userbase_bin / "pip"

    # shlex.quote, not bare double quotes. These paths come from the install
    # location and the app name, so a backtick, $, " or newline in either — an
    # app renamed by the user, a home directory with a quote in it — produced a
    # malformed /bin/sh script that would execute whatever the interpolation
    # opened up. Everything here is generated once and then run by the user's
    # shell, so quoting it is the whole defence.
    common = (
        f"export PYTHONUSERBASE={shlex.quote(str(p.userbase))}\n"
        f"export PIP_CONFIG_FILE={shlex.quote(str(p.pip_conf))}\n"
    )
    bundled_python = shlex.quote(str(p.bundled_python))

    _write_wrapper(
        python_shim,
        '#!/bin/sh\n'
        + common
        + f'exec {bundled_python} "$@"\n',
    )
    # python3 alias
    python3_shim = p.userbase_bin / "python3"
    try:
        # Create under a temporary name and rename over the target: os.replace
        # is atomic, so the shim is never missing and there is no window
        # between "it exists, unlink it" and "now create it" for anything else
        # to occupy.
        tmp_link = python3_shim.with_name(f".python3.{os.getpid()}.tmp")
        tmp_link.unlink(missing_ok=True)
        tmp_link.symlink_to(python_shim)
        os.replace(tmp_link, python3_shim)
    except OSError:
        # File system without symlinks: fall back to a duplicate script.
        tmp_link.unlink(missing_ok=True)
        shutil.copy2(python_shim, python3_shim)

    _write_wrapper(
        pip_shim,
        '#!/bin/sh\n'
        + common
        + f'exec {bundled_python} -m pip "$@"\n',
    )
    pip3_shim = p.userbase_bin / "pip3"
    try:
        # Same temp-name-then-replace as python3 above, and for the same
        # reason: unlinking first leaves a window where `pip3` is simply not on
        # PATH, and these shims are rewritten on every launch while spawned
        # subprocesses are free to be resolving them.
        tmp_link = pip3_shim.with_name(f".pip3.{os.getpid()}.tmp")
        tmp_link.unlink(missing_ok=True)
        tmp_link.symlink_to(pip_shim)
        os.replace(tmp_link, pip3_shim)
    except OSError:
        # File system without symlinks: fall back to a duplicate script.
        tmp_link.unlink(missing_ok=True)
        shutil.copy2(pip_shim, pip3_shim)


def _maybe_install_cli_symlink(p: AppPaths) -> None:
    """If ~/.local/bin exists, expose the bundled CLI wrapper as `<slug>`."""
    target = p.cli_symlink
    src = p.cli_wrapper
    if not target.parent.exists() or not src.exists():
        return
    try:
        if target.is_symlink() or target.exists():
            if target.is_symlink() and target.resolve() == src.resolve():
                return
            target.unlink()
        target.symlink_to(src)
    except OSError:
        # Not fatal — the app runs fine without the `<slug>` shortcut — but
        # silence left "the command is missing from my shell" with nothing to
        # look at. A permission-denied on ~/.local/bin says it in one line.
        log.debug("could not install the CLI symlink at %s", target, exc_info=True)


def setup(p: AppPaths) -> None:
    """One-shot bootstrap: pip.conf + bin/ wrappers + ~/.local/bin symlink."""
    p.userbase.mkdir(parents=True, exist_ok=True)
    p.userbase_bin.mkdir(parents=True, exist_ok=True)
    _write_pip_conf(p)
    _ensure_wrappers(p)
    _maybe_install_cli_symlink(p)


def user_site_packages(p: AppPaths) -> list[str]:
    """The overlay's site-packages directory, spelled out.

    PYTHONUSERBASE is only half the story. The server runs the *app-layer*
    interpreter, and that venv is built with ``ENABLE_USER_SITE = False`` — so
    the overlay is not on its path no matter what PYTHONUSERBASE says, while
    the runtime interpreter the CLI wrapper uses has it enabled. `openkimo pip
    install requests` therefore reported success, `openkimo python -c "import
    requests"` worked, and the agent inside the server still answered
    ModuleNotFoundError.

    Only the directory matching the bundled interpreter. A userbase can hold
    several — a dev run with a different Python leaves its own — and putting
    another version's site-packages on this interpreter's path is worse than
    leaving the overlay off: a C extension built for 3.14 does not load in
    3.12, it raises where the import used to simply fail.
    """
    version = _bundled_python_version(p)
    if version is not None:
        site_packages = p.userbase / "lib" / f"python{version}" / "site-packages"
        return [str(site_packages)] if site_packages.is_dir() else []

    # No version in the layer name — the Windows runtime is just `python`, and
    # its userbase is laid out as `PythonXY/site-packages`. Take it only when
    # there is exactly one: more than one means the same ambiguity this
    # function exists to refuse, and guessing is what breaks the import.
    candidates = sorted(
        d
        for pattern in ("lib/python*/site-packages", "Python*/site-packages")
        for d in p.userbase.glob(pattern)
        if d.is_dir()
    )
    return [str(candidates[0])] if len(candidates) == 1 else []


def _bundled_python_version(p: AppPaths) -> str | None:
    """``3.12`` from a runtime layer named ``cpython-3.12``.

    None when the name carries no version, which is the Windows layout — its
    runtime directory is simply ``python``.
    """
    name = getattr(p, "bundled_python_root", None)
    if name is None:
        return None
    _, _, version = name.name.partition("-")
    return version or None


_PATH_BEGIN = "__OPENKIMO_PATH_BEGIN__"
_PATH_END = "__OPENKIMO_PATH_END__"


@functools.cache
def login_shell_path() -> str:
    """The PATH the user's own login shell sets up, or "" when it cannot be had.

    An app started from Finder or the Dock inherits launchd's PATH —
    /usr/bin:/bin:/usr/sbin:/sbin — and nothing the user installed is on it:
    not Homebrew's node and npm, not nvm, not a pipx bin. The agent's shell
    tool inherits the server's environment, so a skill that runs
    `node scripts/imap.js` answered "node: command not found" in the app while
    the same command worked in Terminal. Asking the login shell once, the way
    a terminal would build it, is how GUI apps on macOS recover that PATH.

    Interactive as well as login, because nvm and many Homebrew setups live
    in .zshrc. The markers fence the value off from anything a profile prints.
    """
    if sys.platform != "darwin":
        return ""
    shell = os.environ.get("SHELL") or "/bin/zsh"
    script = f'printf "%s%s%s" "{_PATH_BEGIN}" "$PATH" "{_PATH_END}"'
    try:
        result = subprocess.run(
            [shell, "-ilc", script],
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        log.warning("Could not read PATH from login shell %s: %s", shell, exc)
        return ""
    begin = result.stdout.rfind(_PATH_BEGIN)
    end = result.stdout.find(_PATH_END, begin)
    if begin < 0 or end < 0:
        log.warning("Login shell %s printed no PATH (exit %s)", shell, result.returncode)
        return ""
    return result.stdout[begin + len(_PATH_BEGIN) : end]


def _merge_path(*parts: str) -> str:
    """Join PATH strings in order, keeping the first occurrence of each entry."""
    seen: set[str] = set()
    entries: list[str] = []
    for part in parts:
        for entry in part.split(os.pathsep):
            if entry and entry not in seen:
                seen.add(entry)
                entries.append(entry)
    return os.pathsep.join(entries)


def env_overlay(p: AppPaths) -> dict[str, str]:
    """Environment additions for any subprocess that should use the overlay.

    Used by `server.py` when spawning uvicorn and by the Install Package…
    pip subprocess.
    """
    sep = os.pathsep
    base_path = os.environ.get("PATH", "")
    overlay = {
        "PYTHONUSERBASE": str(p.userbase),
        "PIP_CONFIG_FILE": str(p.pip_conf),
        # The bundled interpreter stays ahead of everything, so `python` and
        # `pip` are still the app's; the user's own tools come after it.
        "PATH": _merge_path(
            str(p.userbase_bin), str(p.bundled_python_bin), base_path, login_shell_path()
        ),
    }
    # Named explicitly, for the interpreter that ignores user-site. The caller
    # puts the bundled kimi_cli ahead of these, so the overlay adds packages
    # rather than shadowing the app's own.
    sites = user_site_packages(p)
    if sites:
        existing = os.environ.get("PYTHONPATH", "")
        overlay["PYTHONPATH"] = sep.join([*sites, existing] if existing else sites)
    return overlay


def reset(p: AppPaths) -> None:
    """Wipe the user overlay site-packages (kept for the future Reset menu)."""
    site_packages_root = p.userbase / "lib"
    if site_packages_root.exists():
        shutil.rmtree(site_packages_root, ignore_errors=True)
    site_packages_root.mkdir(parents=True, exist_ok=True)
